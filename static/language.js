let currentLanguageSettings = {
  primary_language: "en",
  secondary_languages: []
};

function translate(key, values = {}) {
  const active = languageText[currentLanguageSettings.primary_language] || languageText.en;
  const phrase = active[key] || languageText.en[key] || key;
  return phrase.replace(/\{(\w+)\}/g, (match, name) =>
    Object.prototype.hasOwnProperty.call(values, name) ? values[name] : match
  );
}

function applyLanguage(language) {
  currentLanguageSettings.primary_language = language;
  document.documentElement.lang = language;
  for (const element of document.querySelectorAll("[data-i18n]")) {
    element.textContent = translate(element.dataset.i18n);
  }
  for (const element of document.querySelectorAll("[data-i18n-placeholder]")) {
    element.placeholder = translate(element.dataset.i18nPlaceholder);
  }
  for (const element of document.querySelectorAll("[data-i18n-title]")) {
    element.title = translate(element.dataset.i18nTitle);
  }
  for (const element of document.querySelectorAll("[data-i18n-aria-label]")) {
    element.setAttribute(
      "aria-label",
      translate(element.dataset.i18nAriaLabel)
    );
  }
  document.dispatchEvent(new CustomEvent("languagechange"));
}

function setSecondaryOptions(languages, selectedCodes, primaryLanguage) {
  const select = document.querySelector("#secondary-languages");
  if (!select) return;
  select.replaceChildren();
  for (const language of languages) {
    if (language.code === primaryLanguage) continue;
    const option = document.createElement("option");
    option.value = language.code;
    option.textContent = language.name;
    option.selected = selectedCodes.includes(language.code);
    select.append(option);
  }
}

function selectedSecondaryLanguages() {
  const select = document.querySelector("#secondary-languages");
  return select
    ? Array.from(select.selectedOptions, (option) => option.value)
    : currentLanguageSettings.secondary_languages;
}

async function saveLanguageSettings(primaryLanguage, secondaryLanguages) {
  const response = await fetch("/api/language-settings", {
    method: "PUT",
    headers: {
      "Content-Type": "application/json",
      "X-CSRF-Token": document.querySelector('meta[name="csrf-token"]')?.content || ""
    },
    body: JSON.stringify({
      primary_language: primaryLanguage,
      secondary_languages: secondaryLanguages
    })
  });
  const result = await response.json();
  if (!response.ok) throw new Error(result.error || `Request failed (${response.status})`);
  currentLanguageSettings = result;
  applyLanguage(result.primary_language);
  const primarySelect = document.querySelector("#primary-language");
  if (primarySelect) primarySelect.value = result.primary_language;
  setSecondaryOptions(
    window.supportedLanguages || [],
    result.secondary_languages,
    result.primary_language
  );
  const status = document.querySelector("#language-settings-status");
  if (status) status.textContent = translate("language.saved");
}

async function loadLanguageSettings() {
  const response = await fetch("/api/language-settings");
  if (!response.ok) throw new Error(`Could not load language settings (${response.status})`);
  const result = await response.json();
  currentLanguageSettings = result;
  window.supportedLanguages = result.languages;
  applyLanguage(result.primary_language);
  const primarySelect = document.querySelector("#primary-language");
  if (primarySelect) primarySelect.value = result.primary_language;
  setSecondaryOptions(
    result.languages,
    result.secondary_languages,
    result.primary_language
  );
  if (primarySelect) primarySelect.disabled = false;
  const secondarySelect = document.querySelector("#secondary-languages");
  if (secondarySelect) secondarySelect.disabled = false;
}

const primaryLanguageSelect = document.querySelector("#primary-language");
if (primaryLanguageSelect) {
  primaryLanguageSelect.addEventListener("change", async () => {
    const nextPrimary = primaryLanguageSelect.value;
    const secondaries = selectedSecondaryLanguages().filter(
      (language) => language !== nextPrimary
    );
    setSecondaryOptions(window.supportedLanguages || [], secondaries, nextPrimary);
    try {
      await saveLanguageSettings(nextPrimary, secondaries);
    } catch (error) {
      const status = document.querySelector("#language-settings-status");
      if (status) status.textContent = error.message;
      await loadLanguageSettings();
    }
  });
}

